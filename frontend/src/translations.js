export const DEFAULT_LANGUAGE = "vi";
export const LANGUAGE_STORAGE_KEY = "aquatwin-language";
export const LOCALES = { vi: "vi-VN", en: "en-US" };

export function readLanguage(storage) {
  try {
    const saved = storage().getItem(LANGUAGE_STORAGE_KEY);
    return Object.hasOwn(LOCALES, saved) ? saved : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function translate(language, message, values = {}) {
  const template = language === "vi" && Object.hasOwn(vietnamese, message) ? vietnamese[message] : message;
  return template.replace(/\{(\w+)\}/g, (placeholder, key) => (
    Object.hasOwn(values, key) ? String(values[key]) : placeholder
  ));
}

const runtimeLabels = { all: "All", demo: "Demo", real: "Real", loading: "loading" };
const statusPatterns = [
  [/^Generation (?<current>\d+) of (?<total>\d+)$/, "Generation {current} of {total}"],
  [/^Completed baseline and exhaustive search for (?<scenario>.+)$/, "Completed baseline and exhaustive search for {scenario}"],
  [/^Completed GA seed (?<seed>-?\d+) for (?<scenario>.+)$/, "Completed GA seed {seed} for {scenario}"],
  [/^Request failed with status (?<status>\d+)$/, "Request failed with status {status}"],
];

export function runtimeLabel(t, mode = "loading") {
  return t(Object.hasOwn(runtimeLabels, mode) ? runtimeLabels[mode] : mode);
}

export function valveActionLabel(t, { status, valve_id: valve }) {
  if (status === "CLOSED") return t("Close valve {valve}", { valve });
  if (status === "OPEN") return t("Open valve {valve}", { valve });
  return `${status} ${valve}`;
}

export function localizeStatus(t, message) {
  for (const [pattern, template] of statusPatterns) {
    const match = message.match(pattern);
    if (match) return t(template, match.groups);
  }
  return t(message);
}
